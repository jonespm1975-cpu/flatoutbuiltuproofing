import test from 'node:test';
import assert from 'node:assert/strict';
import {parseProviderId,finishClaim} from './task-161-provider-id.mjs';
const valid={status:'leased',lease_token:'token-A',lease_until:Date.now()+60000,provider_message_id:null};
const accepted=parseProviderId(200,{id:'re_12345678'});
test('provider 200 and valid ID accepted',()=>assert.deepEqual(accepted,{ok:true,id:'re_12345678'}));
test('provider 202 and valid ID accepted',()=>assert.equal(parseProviderId(202,{id:'re_12345678'}).ok,true));
test('provider 400 rejected',()=>assert.equal(parseProviderId(400,{id:'re_12345678'}).ok,false));
test('provider 500 rejected',()=>assert.equal(parseProviderId(500,{id:'re_12345678'}).ok,false));
test('200 without ID rejected',()=>assert.equal(parseProviderId(200,{}).ok,false));
test('200 malformed ID rejected',()=>assert.equal(parseProviderId(200,{id:'bad id'}).ok,false));
test('200 nonobject body rejected',()=>assert.equal(parseProviderId(200,null).ok,false));
test('correct claim commits provider ID',()=>assert.equal(finishClaim(valid,'token-A',accepted).row.provider_message_id,'re_12345678'));
test('wrong token does not commit',()=>assert.equal(finishClaim(valid,'token-B',accepted).ok,false));
test('expired lease does not commit',()=>assert.equal(finishClaim({...valid,lease_until:Date.now()-1},'token-A',accepted).ok,false));
test('accepted status cannot be re-claimed',()=>assert.equal(finishClaim({...valid,status:'accepted'},'token-A',accepted).ok,false));
test('provider error does not commit',()=>assert.equal(finishClaim(valid,'token-A',parseProviderId(500,{})).ok,false));
test('existing different provider ID cannot be overwritten',()=>assert.equal(finishClaim({...valid,provider_message_id:'re_other'},'token-A',accepted).ok,false));
test('original row not mutated',()=>{finishClaim(valid,'token-A',accepted);assert.equal(valid.provider_message_id,null)});
